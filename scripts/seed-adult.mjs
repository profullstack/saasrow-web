#!/usr/bin/env node
// Staff seeding for the Adult (18+) category.
//
//   node scripts/seed-adult.mjs seeds.json > seed.sql
//   docker exec -i <supabase-db container> psql -U postgres -v ON_ERROR_STOP=1 -1 < seed.sql
//
// seeds.json is an array of { name, url, description, tags }. Each becomes a
// free listing in category Adult, approved and badge-exempt (staff-listed, so
// the free tier's badge rule does not hide it). The database trigger moves it
// to status 'adult': live for signed-in members, absent from every public
// surface. A URL that is already listed is skipped, so the file can be re-run.

import { readFileSync } from 'node:fs'

const file = process.argv[2]
if (!file) {
  console.error('Usage: node scripts/seed-adult.mjs <seeds.json>')
  process.exit(2)
}

/** A dollar-quoted SQL string whose tag cannot occur in the text. */
function quote(text) {
  const s = String(text ?? '')
  let tag = 'seed'
  while (s.includes(`$${tag}$`)) tag += 'x'
  return `$${tag}$${s}$${tag}$`
}

const clean = (s, max) => String(s ?? '').replace(/\s+/g, ' ').trim().slice(0, max)

const seeds = JSON.parse(readFileSync(file, 'utf8'))
if (!Array.isArray(seeds)) throw new Error('seeds.json must be an array')

const out = ['-- Adult (18+) seed listings. Generated by scripts/seed-adult.mjs.']
let n = 0
for (const seed of seeds) {
  const name = clean(seed.name, 120)
  const description = clean(seed.description, 2000)
  let url
  try {
    const u = new URL(String(seed.url).trim())
    if (u.protocol !== 'https:' && u.protocol !== 'http:') throw new Error('not http(s)')
    url = u.href.replace(/\/+$/, '')
  } catch {
    console.error(`skipped (bad url): ${seed.name} ${seed.url}`)
    continue
  }
  if (!name || !description) {
    console.error(`skipped (no name or description): ${seed.url}`)
    continue
  }
  const tags = [...new Set((Array.isArray(seed.tags) ? seed.tags : []).map((t) => clean(t, 30).toLowerCase()).filter(Boolean))].slice(0, 8)
  const tagSql = tags.length ? `ARRAY[${tags.map(quote).join(', ')}]::text[]` : `'{}'::text[]`
  out.push(
    `INSERT INTO software_submissions (title, url, description, category, tags, status, tier, badge_exempt)
SELECT ${quote(name)}, ${quote(url)}, ${quote(description)}, 'Adult', ${tagSql}, 'approved', 'free', true
WHERE NOT EXISTS (SELECT 1 FROM software_submissions WHERE url IN (${quote(url)}, ${quote(url + '/')}));`,
  )
  n++
}
out.push(`SELECT status, count(*) FROM software_submissions WHERE category = 'Adult' GROUP BY 1;`)
console.log(out.join('\n\n'))
console.error(`${n} listing(s) written`)
